    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int bayar = Integer.parseInt(jTextField2.getText());
        int kembalian = bayar - total;
        
        jTextArea2.setText("");
        jTextArea2.append("Menu :" + menu + "\n");
        jTextArea2.append("Qty : " + qty + "\n");
        jTextArea2.append("Total : Rp." +total + "\n");
        jTextArea2.append("Bayar : Rp." + bayar + "\n");
        
        if (kembalian >= 0){
            jTextArea2.append("kembalian: Rp." + kembalian + "\n");
        } else {
            jTextArea2.append("Uang Kurang: Rp." + Math.abs(kembalian) + "\n");
        }
        
        
    }//GEN-LAST:event_jButton2ActionPerformed

