    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        if(jComboBox1.getSelectedIndex()==0){
            menu="Ayam Goreng";
            harga=15000;
            jLabel2.setText("Harga:");
            jLabel3.setText("Rp."+harga);
        }
        else if (jComboBox1.getSelectedIndex()==1){
            menu="Ayam Bakar";
            harga=20000;
            jLabel2.setText("Harga");
            jLabel3.setText("Rp."+harga);
        }
        else if (jComboBox1.getSelectedIndex()==2){
            menu="Nasi Goreng";
            harga=12000;
            jLabel2.setText("Harga");
            jLabel3.setText("Rp."+harga);
        }
    }//GEN-LAST:event_jComboBox1ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        menu = jComboBox1.getSelectedItem().toString();
        qty = Integer.parseInt(jTextField1.getText());
        
        if(menu.equals("Ayam Goreng")){
            harga = 20000;
        }
        
        total = harga * qty;
        
        jTextArea1.append("Menu :" + menu +"\n");
        jTextArea1.append("Qty :" + qty +"\n");
        jTextArea1.append("Total :" + total + "\n");
    }//GEN-LAST:event_jButton1ActionPerformed

